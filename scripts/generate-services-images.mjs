/* ------------------------------------------------------------------ *
 *  Services-bento hero image — the Brand Identity card.
 *
 *  Source: Portfolio-15 / 10 YEARS-17, the anniversary lockup running
 *  as building signage. It is the only frame on the site that shows a
 *  mark IN USE rather than on a presentation slide, and the only
 *  identity project (the other fourteen are social, print and app
 *  work).
 *
 *  The source is 16:9, the card is ~0.55 tall, and the bottom 68% of
 *  the card sits under a dark scrim. So the crop is tight and starts
 *  34% down the frame: that lifts the "1e" mark into the top half of
 *  the card, where the scrim is still transparent, and drops the
 *  lockup's own "Beauty & Beyond" wordmark out of the frame instead of
 *  burying it under the title.
 *
 *  Two crops, because the card changes shape:
 *    tall — the 3-column desktop card and the single-column phone card
 *    wide — the 2-column tablet card, where it spans both columns at a
 *           capped height. Wider context, mark biased right of centre
 *           so the text block on the left does not sit on it.
 *
 *  Run: npm run generate:services
 * ------------------------------------------------------------------ */
import { mkdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "public", "services");
mkdirSync(outDir, { recursive: true });

const SOURCE = "Portfolio-15/10 YEARS-17.jpg";

const TARGETS = [
  /* box = [x0, y0, x1, y1] as fractions of the source. */
  { out: "identity-tall.webp", box: [0.2032, 0.3361, 0.4117, 1.0], width: 840 },
  { out: "identity-wide.webp", box: [0.0, 0.24, 0.48, 0.795], width: 1600 },
];

const report = [];
const manifest = [];
for (const t of TARGETS) {
  const src = join(root, "public", SOURCE);
  const meta = await sharp(src).metadata();
  const rect = {
    left: Math.round(t.box[0] * meta.width),
    top: Math.round(t.box[1] * meta.height),
    width: Math.round((t.box[2] - t.box[0]) * meta.width),
    height: Math.round((t.box[3] - t.box[1]) * meta.height),
  };
  const height = Math.round((t.width * rect.height) / rect.width);

  await sharp(src)
    .extract(rect)
    .resize(t.width, height, { kernel: "lanczos3" })
    .webp({ quality: 78, effort: 6 })
    .toFile(join(outDir, t.out));

  report.push(
    `  ${t.out.padEnd(20)} crop ${rect.width}x${rect.height} -> ${t.width}x${height}` +
      `  ${Math.round(statSync(join(outDir, t.out)).size / 1024)}KB`
  );
  manifest.push(`${t.out}  ${t.width}x${height}  <-  ${SOURCE}  box ${t.box.join(",")}`);
}

console.log(`[services] from ${SOURCE}`);
console.log(report.join("\n"));
writeFileSync(
  join(outDir, "MANIFEST.txt"),
  "Generated by scripts/generate-services-images.mjs — do not edit.\nWebP q78.\n\n" +
    manifest.join("\n") +
    "\n"
);
