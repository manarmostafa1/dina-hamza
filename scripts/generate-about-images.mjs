/* ------------------------------------------------------------------ *
 *  About-section showcase images.
 *
 *  The deck shuffles three cards, so they must all share ONE aspect
 *  ratio or the stack changes height between slides. The ratio is 1:1.
 *
 *    1. Dina herself — slide 1 speaks in the first person, so it shows
 *       the person, not a mockup. dina-about.jpg is a phone snapshot:
 *       the top ~41% is sky, an AC unit and blank wall, and there is a
 *       burned-in Instagram avatar at the bottom-left. The box keeps
 *       her and the left canvas (the right one is cut at the frame
 *       edge) and excludes all three. It measures 0.99, so 1:1 is
 *       essentially free. Output at the crop's native 752px rather
 *       than upscaling to 900.
 *    2. An art-directed photo composite, for the copy about turning
 *       individual elements into one complete visual.
 *    3. A brand built from scratch and carried across a system, for
 *       "from a single visual to a complete identity". Deliberately
 *       not the anniversary project — the Services hero below uses it.
 *
 *  Run: npm run generate:about
 * ------------------------------------------------------------------ */
import { mkdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "public", "about");
mkdirSync(outDir, { recursive: true });

const RATIO = 1; // square — the showcase deck. See the note above.
const WIDTH = 900;

const TARGETS = [
  {
    out: "showcase-dina.webp",
    file: "dina-about.jpg",
    box: [0.0, 0.41, 0.65, 0.92],
    width: 752,
  },
  {
    out: "showcase-visual.webp",
    /* Portfolio-13 #2, MY Wellness: figure, laptop, flying papers and
       the leaf motif composited and graded into one scene. The square
       sits 7.5% down so the Arabic headline stays whole. */
    file: "Portfolio-13/WhatsApp Image 2026-07-21 at 11.45.05 AM (1).jpeg",
    box: [0.0, 0.075, 1.0, 0.825],
  },
  {
    out: "showcase-exploring.webp",
    /* Portfolio-14 #0, SKINTRIX 360: the wordmark and the app screens
       it grew into. Source is 853 tall, so it ships at 853, not 900.
       Flush left so the wordmark's ring icon is not clipped. */
    file: "Portfolio-14/WhatsApp Image 2026-07-21 at 11.45.18 AM (1).jpeg",
    box: [0.0, 0.0, 0.667, 1.0],
    width: 853,
  },
];

/** Largest RATIO-shaped rect inside the box, centred. */
function fit(box, meta, ratio) {
  const x0 = Math.round(box[0] * meta.width);
  const y0 = Math.round(box[1] * meta.height);
  const bw = Math.round((box[2] - box[0]) * meta.width);
  const bh = Math.round((box[3] - box[1]) * meta.height);
  let w = bw;
  let h = Math.round(w / ratio);
  if (h > bh) {
    h = bh;
    w = Math.round(h * ratio);
  }
  return {
    left: x0 + Math.round((bw - w) / 2),
    top: y0 + Math.round((bh - h) / 2),
    width: w,
    height: h,
  };
}

const report = [];
for (const t of TARGETS) {
  const src = join(root, "public", t.file);
  const meta = await sharp(src).metadata();
  const ratio = t.ratio ?? RATIO;
  const width = t.width ?? WIDTH;
  const rect = fit(t.box, meta, ratio);
  const height = Math.round(width / ratio);

  await sharp(src)
    .extract(rect)
    .resize(width, height, { fit: "cover", kernel: "lanczos3" })
    .webp({ quality: 78, effort: 6 })
    .toFile(join(outDir, t.out));

  const up = width / rect.width;
  report.push(
    `  ${t.out.padEnd(26)} from ${t.file.split("/").pop().slice(0, 26).padEnd(28)}` +
      ` crop ${rect.width}x${rect.height}  upscale ${up.toFixed(2)}x` +
      `  ${Math.round(statSync(join(outDir, t.out)).size / 1024)}KB`
  );
}

console.log(`[about] deck ratio ${RATIO}:1 at ${WIDTH}px, plus the pair crops`);
console.log(report.join("\n"));
writeFileSync(
  join(outDir, "MANIFEST.txt"),
  "Generated by scripts/generate-about-images.mjs — do not edit.\n" +
    `deck ratio ${RATIO}:1 at ${WIDTH}px, WebP q78.\n\n` +
    TARGETS.map((t) => `${t.out}  ratio ${t.ratio ?? RATIO}  <-  ${t.file}`).join("\n") +
    "\n"
);
